-- Loto Inteligência IA — estrutura inicial do histórico de simulações
-- Execute este arquivo no SQL Editor do projeto Supabase (região São Paulo).
-- O aplicativo Streamlit acessará o banco pelo servidor usando secrets; não exponha
-- a chave service_role/secret em páginas, repositórios ou mensagens.

create table if not exists public.simulations (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    lottery text not null check (lottery in ('Lotofácil', 'Mega-Sena')),
    method text not null check (method in ('Equilibrado', 'Aleatório')),
    ticket_count integer not null check (ticket_count > 0),
    ticket_price numeric(10,2) not null check (ticket_price >= 0),
    investment_total numeric(12,2) not null check (investment_total >= 0),
    draw_contest integer,
    draw_date date,
    draw_numbers integer[],
    evaluated_at timestamptz,
    prize_total numeric(12,2),
    net_balance numeric(12,2),
    status text not null default 'Pendente'
        check (status in ('Pendente', 'Conferida'))
);

create table if not exists public.simulation_games (
    id bigint generated by default as identity primary key,
    simulation_id bigint not null references public.simulations(id) on delete cascade,
    game_number integer not null check (game_number > 0),
    numbers integer[] not null,
    hits integer,
    prize_tier text,
    prize_amount numeric(12,2),
    unique (simulation_id, game_number)
);

create index if not exists simulations_created_at_idx
    on public.simulations (created_at desc);
create index if not exists simulations_lottery_status_idx
    on public.simulations (lottery, status);
create index if not exists simulation_games_simulation_id_idx
    on public.simulation_games (simulation_id);

-- RLS fica ativado sem políticas públicas. O app usa a chave secreta somente
-- no servidor Streamlit (st.secrets), nunca no navegador.
alter table public.simulations enable row level security;
alter table public.simulation_games enable row level security;
